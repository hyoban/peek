package codex

import (
	"strings"
	"testing"
)

func fileDiff(path, body string) string {
	return "diff --git a/" + path + " b/" + path + "\n--- a/" + path + "\n+++ b/" + path + "\n@@ -1 +1 @@\n" + body
}

func TestRankDiffsPutsCodeFirst(t *testing.T) {
	diff := fileDiff("pnpm-lock.yaml", "+lock\n") + fileDiff("README.md", "+docs\n") +
		fileDiff("gen.go", "+// Code generated by gen. DO NOT EDIT.\n") + fileDiff("main.go", "+code\n")
	ranked, complete := rankDiffs(diff, 1<<20)
	if !complete {
		t.Fatal("a diff within the budget is not complete")
	}
	order := []string{"+code", "+docs", "+lock", "DO NOT EDIT"}
	last := -1
	for _, want := range order {
		i := strings.Index(ranked, want)
		if i <= last {
			t.Fatalf("%q out of order:\n%s", want, ranked)
		}
		last = i
	}
}

func TestRankDiffsCutsAndLeavesOut(t *testing.T) {
	big := strings.Repeat("+line\n", 4000)
	ranked, complete := rankDiffs(fileDiff("go.sum", big)+fileDiff("a.go", "+small\n"), 1<<20)
	if !complete || !strings.Contains(ranked, "+small") || !strings.Contains(ranked, "cut here") || len(ranked) > tierCaps[tierBulk]+1024 {
		t.Fatalf("a cut lockfile should not make the diff incomplete (complete %v, %d bytes)", complete, len(ranked))
	}
	ranked, complete = rankDiffs(fileDiff("a.go", big), 1<<20)
	if complete || len(ranked) > tierCaps[tierCode]+100 {
		t.Fatal("a cut code diff is reported complete or past its cap")
	}
	ranked, complete = rankDiffs(fileDiff("a.go", "+first\n")+fileDiff("b.go", "+second\n"), len(fileDiff("a.go", "+first\n")))
	if complete || !strings.Contains(ranked, "+first") || strings.Contains(ranked, "+second") || !strings.Contains(ranked, "left out") {
		t.Fatalf("a diff over budget was not left out:\n%s", ranked)
	}
}

func TestDiffPathReadsQuotedHeaders(t *testing.T) {
	for header, want := range map[string]string{
		"diff --git a/x/y.go b/x/y.go":               "x/y.go",
		`diff --git "a/caf\303\251" "b/caf\303\251"`: `caf\303\251`,
	} {
		if got := diffPath(header + "\n"); got != want {
			t.Errorf("diffPath(%q) = %q, want %q", header, got, want)
		}
	}
}
