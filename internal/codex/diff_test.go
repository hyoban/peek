func fileDiff(path, body string) string {
	return "diff --git a/" + path + " b/" + path + "\n--- a/" + path + "\n+++ b/" + path + "\n@@ -1 +1 @@\n" + body
}

func TestRankDiffsPutsCodeFirst(t *testing.T) {
	diff := fileDiff("pnpm-lock.yaml", "+lock\n") + fileDiff("README.md", "+docs\n") + fileDiff("a_test.go", "+test\n") +
		fileDiff("gen.go", "+// Code generated by gen. DO NOT EDIT.\n") + fileDiff("main.go", "+code\n")
	ranked, complete := rankDiffs(diff, 1<<20, nil)
	if !complete {
		t.Fatal("a diff within the budget is not complete")
	}
	order := []string{"## Code\n", "+code", "## Tests\n", "+test", "## Docs\n", "+docs", "## Lockfiles and generated files\n", "+lock", "DO NOT EDIT"}
	last := -1
	for _, want := range order {
		i := strings.Index(ranked, want)
		if i <= last {
			t.Fatalf("%q out of order:\n%s", want, ranked)
		}
		last = i
	}
}

func TestRankDiffsCutsAndLeavesOut(t *testing.T) {
	big := strings.Repeat("+line\n", 4000)
	ranked, complete := rankDiffs(fileDiff("go.sum", big)+fileDiff("a.go", "+small\n"), 1<<20, nil)
	if !complete || !strings.Contains(ranked, "+small") || !strings.Contains(ranked, "cut here") || len(ranked) > groupCaps[groupBulk]+1024 {
		t.Fatalf("a cut lockfile should not make the diff incomplete (complete %v, %d bytes)", complete, len(ranked))
	}
	ranked, complete = rankDiffs(fileDiff("a.go", big), 1<<20, nil)
	if complete || len(ranked) > groupCaps[filekind.Code]+100 {
		t.Fatal("a cut code diff is reported complete or past its cap")
	}
	ranked, complete = rankDiffs(fileDiff("a.go", "+first\n")+fileDiff("b.go", "+second\n"), len("## Code\n"+fileDiff("a.go", "+first\n")), nil)
	if complete || !strings.Contains(ranked, "+first") || strings.Contains(ranked, "+second") || !strings.Contains(ranked, "left out") {
		t.Fatalf("a diff over budget was not left out:\n%s", ranked)
	}
}

func TestDiffPathReadsQuotedHeaders(t *testing.T) {
	for header, want := range map[string]string{
		"diff --git a/x/y.go b/x/y.go":               "x/y.go",
		`diff --git "a/caf\303\251" "b/caf\303\251"`: `caf\303\251`,
	} {
		if got := diffPath(header + "\n"); got != want {
			t.Errorf("diffPath(%q) = %q, want %q", header, got, want)
		}
	}
}

// .gitattributes decides, either way, over the common rules.
func TestRankDiffsFollowsGeneratedAttribute(t *testing.T) {
	diff := fileDiff("api/client.go", "+marked\n") + fileDiff("dist/app.min.js", "+kept\n") + fileDiff("main.go", "+code\n")
	ranked, _ := rankDiffs(diff, 1<<20, map[string]bool{"api/client.go": true, "dist/app.min.js": false})
	bulk := strings.Index(ranked, "## Lockfiles and generated files")
	if bulk < 0 || strings.Index(ranked, "+marked") < bulk || strings.Index(ranked, "+kept") > bulk || strings.Index(ranked, "+code") > bulk {
		t.Fatalf("attributes not followed:\n%s", ranked)
	}
}

func TestGeneratedMarkerNeedsACommentLine(t *testing.T) {
	for body, want := range map[string]bool{
		"+// Code generated by gen. DO NOT EDIT.\n":           true,
		" # @generated by tool\n":                             true,
		"+ * @generated\n":                                    true,
		"+\tmarker := \"Code generated\" + \"DO NOT EDIT\"\n": false,
		"+text about @generated files\n":                      false,
	} {
		if got := diffGroup(fileDiff("x.go", body), nil) == groupBulk; got != want {
			t.Errorf("%q generated = %v, want %v", body, got, want)
		}
	}
}

// A large diff keeps every hunk's @@ line, which names its function, and
// the first changed lines of each, not only the start of the file.
func TestCutDiffKeepsEveryHunk(t *testing.T) {
	var body strings.Builder
	for i := range 20 {
		body.WriteString("@@ -1 +1 @@ func f" + strconv.Itoa(i) + "()\n context\n")
		for range 50 {
			body.WriteString("+changed in f" + strconv.Itoa(i) + "\n")
		}
	}
	diff := fileDiff("a.go", "")
	diff = diff[:strings.Index(diff, "@@")] + body.String()
	cut := cutDiff(diff, 4096)
	if len(cut) > 4096+200 || strings.Contains(cut, "\n context\n") || !strings.Contains(cut, "cut here") {
		t.Fatalf("cut %d bytes:\n%s", len(cut), cut)
	}
	for i := range 20 {
		f := "func f" + strconv.Itoa(i) + "()"
		if !strings.Contains(cut, f) || !strings.Contains(cut, "+changed in f"+strconv.Itoa(i)) {
			t.Fatalf("%s or its changes missing:\n%s", f, cut)
		}
	}
}
