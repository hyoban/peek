// Command gen builds the package's tables from file-icons
// (https://github.com/file-icons/atom, MIT): its compiled rules, its
// glyphs and its colours. update.sh fetches the sources and runs it.
//
//	go run ./internal/fileicons/gen <icondb.json> <icons.less> <octicons.css>
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"maps"
	"math"
	"os"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

// rule is an entry of file-icons' compiled table of file icons, in the
// order it tries them.
type rule struct {
	Icon   string     `json:"icon"`
	Colour [2]*string `json:"colour"` // for dark themes, then light ones
	Match  struct {
		Source string `json:"source"`
		Flags  string `json:"flags"`
	} `json:"match"`
	Priority  float64 `json:"priority"`
	MatchPath bool    `json:"matchPath"`
}

// glyph is how icons.less draws an icon: a character of an icon font.
type glyph struct {
	font string
	char string
	size float64 // in CSS pixels, for a 16 pixel row
}

// The fonts of icons.less: their families, and the size their glyphs
// take unless one says otherwise.
var fonts = map[string]glyph{
	"octicons": {font: "octicons", size: 16},
	"fa":       {font: "fontawesome", size: 13},
	"mf":       {font: "mfixx", size: 14},
	"devicons": {font: "devopicons", size: 16},
	"fi":       {font: "file-icons", size: 15},
}

func main() {
	if len(os.Args) != 4 {
		log.Fatal("usage: go run ./internal/fileicons/gen <icondb.json> <icons.less> <octicons.css>")
	}
	var rules []rule
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	if err := json.Unmarshal(data, &rules); err != nil {
		log.Fatal(err)
	}
	less, err := os.ReadFile(os.Args[2])
	if err != nil {
		log.Fatal(err)
	}
	glyphs := parseGlyphs(string(less))
	octicons, err := os.ReadFile(os.Args[3])
	if err != nil {
		log.Fatal(err)
	}
	// Rules may name Atom's own icons, of the Octicons it shipped.
	for _, m := range octiconRule.FindAllStringSubmatch(string(octicons), -1) {
		g := fonts["octicons"]
		g.char = cssString(m[2])
		glyphs["icon-"+m[1]] = g
	}

	var b strings.Builder
	b.WriteString("// Code generated by go run ./internal/fileicons/gen; DO NOT EDIT.\n\npackage fileicons\n\n")
	b.WriteString("var rules = []rule{\n")
	used := map[string]bool{"text-icon": true} // the fallback
	colours := map[string]bool{}
	var dropped []string
	for _, r := range rules {
		if _, ok := glyphs[r.Icon]; !ok {
			dropped = append(dropped, r.Icon+": no glyph")
			continue
		}
		source := r.Match.Source
		if o, ok := overrides[source]; ok {
			source = o
		}
		pattern, err := goRegexp(source, r.Match.Flags)
		if err != nil {
			dropped = append(dropped, fmt.Sprintf("%s %s: %v", r.Icon, r.Match.Source, err))
			continue
		}
		used[r.Icon] = true
		dark, light := "", ""
		if r.Colour[0] != nil {
			dark, light = *r.Colour[0], *r.Colour[1]
			colours[dark], colours[light] = true, true
		}
		fmt.Fprintf(&b, "\t{%q, %q, %q, %q, %v, %v},\n", strings.TrimSuffix(r.Icon, "-icon"), dark, light, pattern, r.Priority, r.MatchPath)
	}
	b.WriteString("}\n\n")

	b.WriteString("var glyphs = map[string]glyph{\n")
	names := slices.Sorted(maps.Keys(used))
	for _, name := range names {
		g := glyphs[name]
		fmt.Fprintf(&b, "\t%q: {%q, %q, %v},\n", strings.TrimSuffix(name, "-icon"), g.font, g.char, g.size)
	}
	b.WriteString("}\n\n")

	b.WriteString("// colours holds file-icons' colours for dark themes, then light ones.\nvar colours = map[string][2]string{\n")
	for _, name := range slices.Sorted(maps.Keys(colours)) {
		dark, light := colour(name)
		fmt.Fprintf(&b, "\t%q: {%q, %q},\n", name, dark, light)
	}
	b.WriteString("}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("internal/fileicons/tables.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%d rules, %d glyphs, %d colours\n", len(rules)-len(dropped), len(used), len(colours))
	for _, d := range dropped {
		fmt.Println("dropped", d)
	}
}

