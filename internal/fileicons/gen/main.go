var glyphRule = regexp.MustCompile(`^\.([A-Za-z0-9_-]+-icon):before\s*\{\s*\.([a-z]+);\s*content:\s*"((?:[^"\\]|\\.)+)";([^}]*)\}`)
var fontSize = regexp.MustCompile(`font-size:\s*([0-9.]+)px`)

func parseGlyphs(less string) map[string]glyph {
	glyphs := map[string]glyph{}
	for line := range strings.Lines(less) {
		m := glyphRule.FindStringSubmatch(strings.TrimSpace(line))
		if m == nil {
			continue
		}
		g, ok := fonts[m[2]]
		if !ok {
			log.Fatalf("unknown font mixin .%s in %s", m[2], line)
		}
		g.char = cssString(m[3])
		if p := fontSize.FindStringSubmatch(m[4]); p != nil {
			g.size, _ = strconv.ParseFloat(p[1], 64)
		}
		glyphs[m[1]] = g
	}
	return glyphs
}

// cssString unescapes a CSS string's escapes: \ and up to six hex digits
// for a code point, or \ and a character for that character.
func cssString(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		if s[i] != '\\' || i == len(s)-1 {
			b.WriteByte(s[i])
			continue
		}
		j := i + 1
		for j < len(s) && j < i+7 && strings.ContainsRune("0123456789abcdefABCDEF", rune(s[j])) {
			j++
		}
		if j == i+1 {
			b.WriteByte(s[j])
			i = j
			continue
		}
		r, _ := strconv.ParseUint(s[i+1:j], 16, 32)
		b.WriteRune(rune(r))
		if j < len(s) && s[j] == ' ' {
			j++
		}
		i = j - 1
	}
	return b.String()
}

var jsUnicode = regexp.MustCompile(`\\u([0-9a-fA-F]{4})|\\u\{([0-9a-fA-F]+)\}`)

// goRegexp turns a JavaScript pattern into one Go compiles, where it can.
func goRegexp(source, flags string) (string, error) {
	p := jsUnicode.ReplaceAllStringFunc(source, func(m string) string {
		sub := jsUnicode.FindStringSubmatch(m)
		return `\x{` + sub[1] + sub[2] + `}`
	})
	if strings.Contains(flags, "i") {
		p = "(?i)" + p
	}
	_, err := regexp.Compile(p)
	return p, err
}

// The palette of colours.less: Base16's, each in three tones.
var palette = map[string]string{
	"red": "#ac4142", "green": "#90a959", "yellow": "#f4bf75", "blue": "#6a9fb5",
	"maroon": "#8f5536", "purple": "#aa759f", "orange": "#d28445", "cyan": "#75b5aa",
	"pink": "#ff00cc", "grey": "#7f7f7f",
}

// adjust is how colours.less mends a colour for a background it would be
// hard to see on: darker on light themes, brighter on dark ones.
var adjust = map[string]struct {
	darken, brighten float64
	grey             bool
}{
	"dark-red": {brighten: 15}, "light-green": {darken: 5}, "light-yellow": {darken: 23},
	"medium-yellow": {darken: 15}, "dark-yellow": {darken: 10}, "light-blue": {darken: 18},
	"dark-maroon": {brighten: 8}, "light-orange": {darken: 8}, "light-cyan": {darken: 18},
	"dark-pink": {brighten: 5}, "dark-grey": {brighten: 15, grey: true},
}

func colour(name string) (dark, light string) {
	tone, hue, ok := strings.Cut(name, "-")
	base, known := palette[hue]
	if !ok || !known {
		log.Fatalf("unknown colour %s", name)
	}
	h, s, l := hsl(base)
	switch tone {
	case "light":
		l += 15
	case "dark":
		l -= 15
	}
	dark, light = hex(h, s, l), hex(h, s, l)
	a := adjust[name]
	if a.darken > 0 {
		light = hex(h, s, l-a.darken)
	}
	if a.brighten > 0 {
		if a.grey {
			dark = hex(h, s, l+a.brighten)
		} else {
			dark = hex(h, s+a.brighten, l+a.brighten)
		}
	}
	return dark, light
}

func hsl(hexColour string) (h, s, l float64) {
	v, _ := strconv.ParseUint(hexColour[1:], 16, 32)
	r, g, b := float64(v>>16&0xff)/255, float64(v>>8&0xff)/255, float64(v&0xff)/255
	mx, mn := math.Max(r, math.Max(g, b)), math.Min(r, math.Min(g, b))
	l = (mx + mn) / 2
	if mx != mn {
		d := mx - mn
		if l > 0.5 {
			s = d / (2 - mx - mn)
		} else {
			s = d / (mx + mn)
		}
		switch mx {
		case r:
			h = (g - b) / d
			if g < b {
				h += 6
			}
		case g:
			h = (b-r)/d + 2
		default:
			h = (r-g)/d + 4
		}
		h *= 60
	}
	return h, s * 100, l * 100
}

func hex(h, s, l float64) string {
	s, l = math.Max(0, math.Min(100, s))/100, math.Max(0, math.Min(100, l))/100
	c := (1 - math.Abs(2*l-1)) * s
	x := c * (1 - math.Abs(math.Mod(h/60, 2)-1))
	m := l - c/2
	var r, g, b float64
	switch {
	case h < 60:
		r, g = c, x
	case h < 120:
		r, g = x, c
	case h < 180:
		g, b = c, x
	case h < 240:
		g, b = x, c
	case h < 300:
		r, b = x, c
	default:
		r, b = c, x
	}
	to := func(v float64) int { return int(math.Round((v + m) * 255)) }
	return fmt.Sprintf("#%02x%02x%02x", to(r), to(g), to(b))
}
